export const ERROR_VARIANTS = families.length * locations.length;
export function diagnosticAt(index: number) {
  const normalized =
    ((Math.floor(index) % ERROR_VARIANTS) + ERROR_VARIANTS) % ERROR_VARIANTS;
  const [label, message] =
    families[Math.floor(normalized / locations.length)].split("|");
  const location = locations[normalized % locations.length];
  return {
    label,
    detail: `${message} · ${location}:${3 + (normalized % 197)}`,
  };
}
